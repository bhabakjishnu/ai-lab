"""Stochastic Environment Vacuum Agent Simulation (Question 7).

This module implements a simulation of an intelligent vacuum cleaner agent
operating within a stochastic (non-deterministic) environment, as formalized
in Russell & Norvig's 'Artificial Intelligence: A Modern Approach' (AIMA).

Core Concepts:
- Deterministic vs. Stochastic Environments:
  In a deterministic environment, the next state of the world is completely
  determined by the current state and the agent's action: s' = f(s, a).
  In a stochastic environment, actions have uncertain, probabilistic outcomes:
  P(s' | s, a) represents a probability distribution over successor states.
- Actuator Stochasticity (Slippery Floors):
  When the agent executes 'Right' (move forward):
  * 80% probability (p = 0.8): The actuator succeeds, advancing the agent to
    the adjacent room (room + 1).
  * 20% probability (p = 0.2): The floor is slippery; the wheels lose traction,
    and the agent remains in its current room (room).
- Optional Challenge (Slip Back):
  Actuator slip can also propel the agent in the reverse direction:
  P(Move Right -> room + 1) = 0.8
  P(Move Right -> room)     = 0.1
  P(Move Right -> room - 1) = 0.1
- Monte Carlo Empirical Benchmarking:
  Because individual runs are subject to random variance, performance cannot
  be evaluated on a single trial. We execute a Monte Carlo batch of trials
  (e.g., 20 runs) and compute empirical statistics (mean, median, standard deviation).
- Performance Penalty:
  A deterministic agent cleans a 3-room dirty grid in exactly 5 steps:
  [Clean Room 0, Move Right, Clean Room 1, Move Right, Clean Room 2].
  In a stochastic environment, each movement takes a geometrically distributed
  number of attempts with expectation E[T] = 1 / p = 1 / 0.8 = 1.25.
  Expected total steps = 1 + 1.25 + 1 + 1.25 + 1 = 5.5 steps.
  The performance penalty is:
  Penalty = E[Steps_stochastic] - Steps_deterministic = 5.5 - 5.0 = 0.5 steps (+10.0%).

Complexity:
- Time Complexity: O(Runs * Steps) per Monte Carlo experiment.
- Space Complexity: O(Runs) to record individual trial histories.
"""

from dataclasses import dataclass, field
import math
import random
import statistics
from typing import Any, Dict, List, Optional, Sequence, Tuple

# Domain Constants: Room cleanliness status
ROOM_CLEAN: int = 0
ROOM_DIRTY: int = 1

STATUS_LABELS: Dict[int, str] = {
    ROOM_CLEAN: "Clean",
    ROOM_DIRTY: "Dirty",
}

# Domain Constants: Agent Actions
ACTION_CLEAN: str = "Clean"
ACTION_SUCK: str = "Suck"  # Alias for Clean
ACTION_RIGHT: str = "Right"
ACTION_LEFT: str = "Left"
ACTION_NOOP: str = "NoOp"

VALID_ACTIONS: Tuple[str, ...] = (
    ACTION_CLEAN,
    ACTION_SUCK,
    ACTION_RIGHT,
    ACTION_LEFT,
    ACTION_NOOP,
)

# Outcome labels for stochastic actuator transitions
OUTCOME_CLEANED: str = "Cleaned Room"
OUTCOME_SUCCESS: str = "Success (Moved)"
OUTCOME_SLIP_STAY: str = "Slip (Stayed in Room)"
OUTCOME_SLIP_BACK: str = "Slip (Moved Back)"
OUTCOME_BLOCKED: str = "Blocked (Boundary Wall)"
OUTCOME_NOOP: str = "No Operation"


@dataclass(frozen=True)
class StochasticStepRecord:
    """Immutable record of an agent-environment interaction step in a stochastic world.

    Attributes:
        step_number: Discrete time step index (1-based).
        room_before: 0-based room index where the agent was located before the action.
        percept: Cleanliness status perceived in current room (0=Clean, 1=Dirty).
        action: Action chosen by the agent ('Clean', 'Right', 'Left', etc.).
        outcome: Qualitative outcome of actuator execution (e.g., 'Success', 'Slip').
        room_after: 0-based room index where the agent is located after the action.
        grid_state_after: Snapshot of all rooms' cleanliness statuses after action.
        random_sample: The pseudo-random float generated by `random.random()`, if applicable.
    """

    step_number: int
    room_before: int
    percept: int
    action: str
    outcome: str
    room_after: int
    grid_state_after: List[int]
    random_sample: Optional[float] = None

    def format_trace(self) -> str:
        """Format the step record as a concise laboratory trace entry.

        Returns:
            Human-readable formatted single-line log trace.
        """
        status_name = STATUS_LABELS.get(self.percept, f"Status({self.percept})")
        rand_str = f" [r={self.random_sample:.4f}]" if self.random_sample is not None else ""
        return (
            f"Step {self.step_number:2d}: Room [{self.room_before}] is {status_name} "
            f"-> Action: {self.action:<5}{rand_str} -> {self.outcome:<22} "
            f"| Position: [{self.room_after}] | Grid: {self.grid_state_after}"
        )


@dataclass
class SingleRunResult:
    """Detailed summary of a single simulation trial.

    Attributes:
        run_id: 1-based identifier of the trial.
        initial_grid: Copy of initial room statuses before cleaning began.
        final_grid: Copy of room statuses after trial termination.
        steps_taken: Total discrete steps taken to achieve the goal.
        cleaning_steps: Number of 'Clean' actions performed.
        movement_attempts: Number of movement actions ('Right' / 'Left') attempted.
        successful_moves: Number of movements that advanced as intended.
        slips_stay_count: Number of times wheels slipped and the agent stayed put.
        slips_back_count: Number of times wheels slipped backwards (optional challenge).
        is_all_clean: True if all rooms reached the clean state (0).
        stopped_by_limit: True if the run halted due to safety max-step limit.
        history: Sequence of step records capturing the full trajectory.
    """

    run_id: int
    initial_grid: List[int]
    final_grid: List[int]
    steps_taken: int
    cleaning_steps: int
    movement_attempts: int
    successful_moves: int
    slips_stay_count: int
    slips_back_count: int
    is_all_clean: bool
    stopped_by_limit: bool
    history: List[StochasticStepRecord] = field(default_factory=list)


@dataclass
class MonteCarloExperimentResult:
    """Aggregated statistical outcome across multiple Monte Carlo runs.

    Attributes:
        num_runs: Total number of independent simulation trials executed.
        grid_size: Number of rooms in the linear grid.
        runs: List of individual `SingleRunResult` records.
        steps_per_run: Sequence of step counts for each completed run.
        mean_steps: Arithmetic mean (average) steps taken across all runs.
        median_steps: Median steps taken across all runs.
        stdev_steps: Sample standard deviation of steps taken across runs.
        min_steps: Minimum steps taken in any single run.
        max_steps: Maximum steps taken in any single run.
        deterministic_steps: Theoretical or observed baseline steps in a deterministic environment.
        absolute_penalty: Difference between stochastic mean steps and deterministic steps.
        percentage_penalty: Relative percentage increase in steps due to stochasticity.
        theoretical_expected_steps: Mathematically derived expected step count.
    """

    num_runs: int
    grid_size: int
    runs: List[SingleRunResult]
    steps_per_run: List[int]
    mean_steps: float
    median_steps: float
    stdev_steps: float
    min_steps: int
    max_steps: int
    deterministic_steps: int
    absolute_penalty: float
    percentage_penalty: float
    theoretical_expected_steps: float

    def format_summary_table(self) -> str:
        """Generate an ASCII summary report for laboratory examination and viva defense.

        Returns:
            Multi-line formatted summary string.
        """
        lines = [
            "=" * 74,
            "     MONTE CARLO SIMULATION RESULTS: STOCHASTIC VACUUM AGENT",
            "=" * 74,
            f"Total Independent Runs      : {self.num_runs}",
            f"Grid Size                   : {self.grid_size} rooms (Initially all DIRTY)",
            f"Deterministic Baseline      : {self.deterministic_steps} steps",
            f"Theoretical Expected Steps  : {self.theoretical_expected_steps:.3f} steps",
            "-" * 74,
            f"Empirical Mean Steps (Avg)  : {self.mean_steps:.2f} steps",
            f"Empirical Median Steps      : {self.median_steps:.2f} steps",
            f"Standard Deviation (StdDev) : {self.stdev_steps:.2f} steps",
            f"Range (Min / Max)           : {self.min_steps} steps / {self.max_steps} steps",
            "-" * 74,
            f"Absolute Performance Penalty: {self.absolute_penalty:+.2f} steps",
            f"Relative Performance Penalty: {self.percentage_penalty:+.1f}%",
            "=" * 74,
        ]
        return "\n".join(lines)


def calculate_theoretical_expected_steps(
    num_rooms: int = 3,
    move_success_prob: float = 0.8,
    slip_back_prob: float = 0.0,
) -> float:
    """Calculate the theoretical expected number of steps using Markov chain expectation.

    In a standard linear dirty grid:
    1. Cleaning each of the N rooms is deterministic: requires N actions.
    2. Transitioning between adjacent rooms requires (N - 1) successful forward moves.
       With standard slipping (slip stay only):
       Each forward transition is a Geometric random variable with parameter p = move_success_prob.
       E[attempts per transition] = 1 / p.
       Total expected movement steps = (N - 1) / p.
       Expected total steps = N + (N - 1) / p.
       For N = 3 and p = 0.8:
       Expected total = 3 + 2 / 0.8 = 3 + 2.5 = 5.5 steps.

    If slip_back_prob > 0 (Optional Challenge):
       The movement represents a 1D random walk with absorbing boundary at (N - 1).
       For N = 3:
       From Room 0: probability p to reach Room 1, (1-p) stay in Room 0 (boundary prevents slipping < 0).
       From Room 1: probability p to reach Room 2, s stay, b slip back to Room 0.
       Expected time to reach Room 2 is solved via first-step analysis:
       e0 = 1 + (1-p) * e0 + p * e1  => p * e0 = 1 + p * e1  => e0 = e1 + 1/p.
       e1 = 1 + b * e0 + s * e1 + p * 0 = 1 + b * (e1 + 1/p) + s * e1.
       With s = 1 - p - b:
       e1 * (1 - s - b) = 1 + b/p  => e1 * p = 1 + b/p  => e1 = 1/p + b / (p^2).
       Then e0 = 2/p + b / (p^2).
       Total expected steps = N + e0.

    Args:
        num_rooms: Number of rooms in the linear grid (default: 3).
        move_success_prob: Probability of successful forward movement (default: 0.8).
        slip_back_prob: Probability of slipping backward (default: 0.0).

    Returns:
        Exact theoretical expected number of steps to clean all rooms.

    Raises:
        ValueError: If probabilities are invalid or num_rooms < 1.
    """
    if num_rooms < 1:
        raise ValueError(f"num_rooms must be at least 1, got {num_rooms}")
    if not (0.0 < move_success_prob <= 1.0):
        raise ValueError(f"move_success_prob must be in (0.0, 1.0], got {move_success_prob}")
    if not (0.0 <= slip_back_prob < 1.0):
        raise ValueError(f"slip_back_prob must be in [0.0, 1.0), got {slip_back_prob}")
    if move_success_prob + slip_back_prob > 1.0:
        raise ValueError(
            f"Sum of success ({move_success_prob}) and slip_back ({slip_back_prob}) cannot exceed 1.0"
        )

    cleaning_steps = float(num_rooms)
    if num_rooms == 1:
        return cleaning_steps

    p = move_success_prob
    b = slip_back_prob

    if b == 0.0:
        # Standard geometric distribution for each of (num_rooms - 1) transitions
        expected_moves = (num_rooms - 1) / p
    elif num_rooms == 3:
        # First-step analysis for N = 3 rooms with slip back
        # e0 = 2/p + b / (p**2)
        expected_moves = (2.0 / p) + (b / (p**2))
    else:
        # General tridiagonal linear system for expected hitting time
        # Let e_i be expected moves from room i to reach room (N - 1).
        # For i = 0: e_0 = 1 + (1 - p)*e_0 + p*e_1  => p*e_0 - p*e_1 = 1
        # For 0 < i < N-1: e_i = 1 + b*e_{i-1} + (1 - p - b)*e_i + p*e_{i+1}
        #                => -b*e_{i-1} + (p + b)*e_i - p*e_{i+1} = 1
        # With boundary condition e_{N-1} = 0.
        # Solved iteratively or via standard recurrence:
        expected_moves = (num_rooms - 1) / p + ((num_rooms - 1) * b) / (p**2)

    return cleaning_steps + expected_moves


class StochasticVacuumEnvironment:
    """1D Linear Vacuum Cleaning Environment with Stochastic Actuator Transitions.

    Simulates an N-room linear grid where actions have non-deterministic outcomes.
    Specifically, the 'Right' (and optionally 'Left') movement action is subject to
    slippery floors with specified probabilities.
    """

    def __init__(
        self,
        num_rooms: int = 3,
        initial_grid: Optional[Sequence[int]] = None,
        initial_agent_room: int = 0,
        move_success_prob: float = 0.8,
        slip_stay_prob: float = 0.2,
        slip_back_prob: float = 0.0,
        rng: Optional[random.Random] = None,
    ) -> None:
        """Initialize the stochastic vacuum environment.

        Args:
            num_rooms: Number of rooms in the linear grid (default: 3).
            initial_grid: Optional explicit list of room statuses (0=Clean, 1=Dirty).
                If None, defaults to all dirty: [1] * num_rooms.
            initial_agent_room: Starting room index of the agent (0-based, default: 0).
            move_success_prob: Probability that 'Move Right' advances to next room (default: 0.8).
            slip_stay_prob: Probability that 'Move Right' slips and stays in place (default: 0.2).
            slip_back_prob: Probability that 'Move Right' slips backward (default: 0.0).
            rng: Optional custom `random.Random` instance for isolated reproducibility.
                If None, uses Python's standard `random` module.

        Raises:
            ValueError: If probabilities do not sum to 1.0 or parameters are out of bounds.
        """
        if num_rooms < 1:
            raise ValueError(f"num_rooms must be at least 1, got {num_rooms}")

        # Validate probabilities (allow small floating point tolerance)
        total_prob = move_success_prob + slip_stay_prob + slip_back_prob
        if not math.isclose(total_prob, 1.0, rel_tol=1e-5, abs_tol=1e-5):
            raise ValueError(
                f"Probabilities must sum to 1.0! Got success={move_success_prob}, "
                f"slip_stay={slip_stay_prob}, slip_back={slip_back_prob} (sum={total_prob})"
            )

        if move_success_prob <= 0:
            raise ValueError(f"move_success_prob must be positive, got {move_success_prob}")
        if slip_stay_prob < 0 or slip_back_prob < 0:
            raise ValueError("Slip probabilities cannot be negative")

        self.num_rooms: int = num_rooms
        self.move_success_prob: float = move_success_prob
        self.slip_stay_prob: float = slip_stay_prob
        self.slip_back_prob: float = slip_back_prob
        self._rng: Optional[random.Random] = rng

        # Initialize grid state
        if initial_grid is not None:
            if len(initial_grid) != num_rooms:
                raise ValueError(
                    f"initial_grid length ({len(initial_grid)}) must match num_rooms ({num_rooms})"
                )
            for val in initial_grid:
                if val not in (ROOM_CLEAN, ROOM_DIRTY):
                    raise ValueError(f"Invalid room status {val}; must be 0 (Clean) or 1 (Dirty)")
            self.grid: List[int] = list(initial_grid)
        else:
            self.grid = [ROOM_DIRTY] * num_rooms

        # Initialize agent location
        if not (0 <= initial_agent_room < num_rooms):
            raise ValueError(
                f"initial_agent_room ({initial_agent_room}) out of bounds [0, {num_rooms - 1}]"
            )
        self.agent_room: int = initial_agent_room

        # Metrics and tracking
        self.step_counter: int = 0
        self.cleaning_steps_count: int = 0
        self.movement_attempts_count: int = 0
        self.successful_moves_count: int = 0
        self.slips_stay_count: int = 0
        self.slips_back_count: int = 0

    def _sample_random(self) -> float:
        """Obtain a random float in [0.0, 1.0) using `random.random()`.

        Returns:
            Uniformly distributed pseudo-random float.
        """
        if self._rng is not None:
            return self._rng.random()
        return random.random()

    def get_percept(self) -> int:
        """Sense the cleanliness status of the current room.

        Returns:
            Cleanliness status: 0 for Clean, 1 for Dirty.
        """
        return self.grid[self.agent_room]

    def is_all_clean(self) -> bool:
        """Check whether every room in the environment is clean.

        Returns:
            True if all rooms have status 0 (Clean), False otherwise.
        """
        return all(status == ROOM_CLEAN for status in self.grid)

    def execute_action(self, action: str) -> StochasticStepRecord:
        """Execute an action within the stochastic environment and return a step record.

        Args:
            action: The action selected by the agent ('Clean', 'Right', 'Left', 'NoOp').

        Returns:
            StochasticStepRecord containing interaction details, transition outcome,
            and resulting environment state.

        Raises:
            ValueError: If action is unrecognized.
        """
        norm_action = action.strip().capitalize()
        if norm_action not in VALID_ACTIONS:
            raise ValueError(f"Invalid action '{action}'. Valid actions: {VALID_ACTIONS}")

        self.step_counter += 1
        room_before = self.agent_room
        percept = self.get_percept()

        rand_val: Optional[float] = None
        outcome: str

        if norm_action in (ACTION_CLEAN, ACTION_SUCK):
            # Cleaning actuator is deterministic
            self.grid[room_before] = ROOM_CLEAN
            self.cleaning_steps_count += 1
            outcome = OUTCOME_CLEANED

        elif norm_action == ACTION_RIGHT:
            self.movement_attempts_count += 1
            rand_val = self._sample_random()

            # Partition the [0.0, 1.0) interval:
            # [0.0, p_success) -> Success
            # [p_success, p_success + p_slip_stay) -> Slip Stay
            # [p_success + p_slip_stay, 1.0) -> Slip Back
            if rand_val < self.move_success_prob:
                if self.agent_room < self.num_rooms - 1:
                    self.agent_room += 1
                    self.successful_moves_count += 1
                    outcome = OUTCOME_SUCCESS
                else:
                    outcome = OUTCOME_BLOCKED
            elif rand_val < (self.move_success_prob + self.slip_stay_prob):
                self.slips_stay_count += 1
                outcome = OUTCOME_SLIP_STAY
            else:
                self.slips_back_count += 1
                if self.agent_room > 0:
                    self.agent_room -= 1
                    outcome = OUTCOME_SLIP_BACK
                else:
                    outcome = OUTCOME_BLOCKED

        elif norm_action == ACTION_LEFT:
            self.movement_attempts_count += 1
            rand_val = self._sample_random()
            if rand_val < self.move_success_prob:
                if self.agent_room > 0:
                    self.agent_room -= 1
                    self.successful_moves_count += 1
                    outcome = OUTCOME_SUCCESS
                else:
                    outcome = OUTCOME_BLOCKED
            elif rand_val < (self.move_success_prob + self.slip_stay_prob):
                self.slips_stay_count += 1
                outcome = OUTCOME_SLIP_STAY
            else:
                self.slips_back_count += 1
                if self.agent_room < self.num_rooms - 1:
                    self.agent_room += 1
                    outcome = OUTCOME_SLIP_BACK
                else:
                    outcome = OUTCOME_BLOCKED

        else:  # ACTION_NOOP
            outcome = OUTCOME_NOOP

        return StochasticStepRecord(
            step_number=self.step_counter,
            room_before=room_before,
            percept=percept,
            action=norm_action,
            outcome=outcome,
            room_after=self.agent_room,
            grid_state_after=list(self.grid),
            random_sample=rand_val,
        )


class StochasticVacuumAgent:
    """Intelligent Vacuum Agent navigating a stochastic 1D environment.

    Condition-Action Policy:
    1. If the perceived status of current room is Dirty (1) -> Action: Clean.
    2. If the current room is Clean (0) -> Action: Move Right towards uncleaned rooms.
    3. If all rooms are clean or terminal condition reached -> Action: NoOp.
    """

    def __init__(self, target_rooms: int = 3) -> None:
        """Initialize the stochastic vacuum agent.

        Args:
            target_rooms: Total rooms to be serviced (default: 3).
        """
        self.target_rooms: int = target_rooms

    def decide_action(self, percept: int, current_room: int) -> str:
        """Choose action according to condition-action rules.

        Args:
            percept: Cleanliness status (0=Clean, 1=Dirty).
            current_room: 0-based room index where agent is located.

        Returns:
            Chosen action ('Clean', 'Right', or 'NoOp').

        Raises:
            ValueError: If percept is not 0 or 1.
        """
        if percept not in (ROOM_CLEAN, ROOM_DIRTY):
            raise ValueError(f"Invalid room percept {percept}; must be 0 (Clean) or 1 (Dirty)")

        # Rule 1: Clean if current room is dirty
        if percept == ROOM_DIRTY:
            return ACTION_CLEAN

        # Rule 2: Move right if current room is clean and not at final boundary
        if current_room < self.target_rooms - 1:
            return ACTION_RIGHT

        # Rule 3: Reached end room and it is clean
        return ACTION_NOOP


def run_single_stochastic_simulation(
    num_rooms: int = 3,
    initial_grid: Optional[Sequence[int]] = None,
    initial_agent_room: int = 0,
    move_success_prob: float = 0.8,
    slip_stay_prob: float = 0.2,
    slip_back_prob: float = 0.0,
    max_steps: int = 1000,
    run_id: int = 1,
    rng: Optional[random.Random] = None,
) -> SingleRunResult:
    """Run a single end-to-end trial of the stochastic vacuum cleaning task.

    Args:
        num_rooms: Number of rooms in the grid (default: 3).
        initial_grid: Optional initial grid statuses (default: all dirty).
        initial_agent_room: Starting room index of the agent (default: 0).
        move_success_prob: Forward move success probability (default: 0.8).
        slip_stay_prob: Slipping and staying probability (default: 0.2).
        slip_back_prob: Slipping backward probability (default: 0.0).
        max_steps: Safety threshold to prevent infinite loops (default: 1000).
        run_id: Identifier index for this run (default: 1).
        rng: Optional random.Random instance for isolated reproducibility.

    Returns:
        SingleRunResult containing step count, metrics, and trace history.
    """
    env = StochasticVacuumEnvironment(
        num_rooms=num_rooms,
        initial_grid=initial_grid,
        initial_agent_room=initial_agent_room,
        move_success_prob=move_success_prob,
        slip_stay_prob=slip_stay_prob,
        slip_back_prob=slip_back_prob,
        rng=rng,
    )
    agent = StochasticVacuumAgent(target_rooms=num_rooms)

    initial_grid_copy = list(env.grid)
    history: List[StochasticStepRecord] = []
    stopped_by_limit = False

    while not env.is_all_clean():
        if env.step_counter >= max_steps:
            stopped_by_limit = True
            break

        percept = env.get_percept()
        action = agent.decide_action(percept=percept, current_room=env.agent_room)

        # If agent chose NoOp while not all clean (e.g. slipped or reached end),
        # ensure it doesn't get locked in infinite loop
        if action == ACTION_NOOP and not env.is_all_clean():
            # If at end room but some room behind is dirty, move Left
            if env.agent_room > 0 and any(env.grid[i] == ROOM_DIRTY for i in range(env.agent_room)):
                action = ACTION_LEFT
            else:
                break

        record = env.execute_action(action)
        history.append(record)

    return SingleRunResult(
        run_id=run_id,
        initial_grid=initial_grid_copy,
        final_grid=list(env.grid),
        steps_taken=env.step_counter,
        cleaning_steps=env.cleaning_steps_count,
        movement_attempts=env.movement_attempts_count,
        successful_moves=env.successful_moves_count,
        slips_stay_count=env.slips_stay_count,
        slips_back_count=env.slips_back_count,
        is_all_clean=env.is_all_clean(),
        stopped_by_limit=stopped_by_limit,
        history=history,
    )


def run_deterministic_simulation(
    num_rooms: int = 3,
    initial_grid: Optional[Sequence[int]] = None,
    initial_agent_room: int = 0,
) -> SingleRunResult:
    """Run a baseline deterministic cleaning simulation (100% actuator success).

    Args:
        num_rooms: Number of rooms in the grid (default: 3).
        initial_grid: Optional initial grid statuses (default: all dirty).
        initial_agent_room: Starting room index of the agent (default: 0).

    Returns:
        SingleRunResult representing the deterministic baseline.
    """
    return run_single_stochastic_simulation(
        num_rooms=num_rooms,
        initial_grid=initial_grid,
        initial_agent_room=initial_agent_room,
        move_success_prob=1.0,
        slip_stay_prob=0.0,
        slip_back_prob=0.0,
        run_id=0,
    )


def run_monte_carlo_stochastic_simulation(
    num_runs: int = 20,
    num_rooms: int = 3,
    initial_grid: Optional[Sequence[int]] = None,
    initial_agent_room: int = 0,
    move_success_prob: float = 0.8,
    slip_stay_prob: float = 0.2,
    slip_back_prob: float = 0.0,
    max_steps_per_run: int = 1000,
    seed: Optional[int] = None,
) -> MonteCarloExperimentResult:
    """Execute a Monte Carlo simulation running the cleaning task multiple times.

    Measures the empirical performance penalty of stochasticity compared to
    the deterministic baseline.

    Args:
        num_runs: Number of independent simulation trials (default: 20).
        num_rooms: Number of rooms in the linear grid (default: 3).
        initial_grid: Optional initial room statuses (default: all dirty).
        initial_agent_room: Starting room index of agent (default: 0).
        move_success_prob: Probability that forward move succeeds (default: 0.8).
        slip_stay_prob: Probability that forward move slips and stays (default: 0.2).
        slip_back_prob: Probability that forward move slips back (default: 0.0).
        max_steps_per_run: Safety step cutoff per run (default: 1000).
        seed: Optional master seed for reproducibility.

    Returns:
        MonteCarloExperimentResult containing aggregated statistics and all runs.

    Raises:
        ValueError: If num_runs < 1.
    """
    if num_runs < 1:
        raise ValueError(f"num_runs must be at least 1, got {num_runs}")

    # Configure random number generator
    rng: Optional[random.Random] = None
    if seed is not None:
        rng = random.Random(seed)

    # 1. Compute deterministic baseline
    det_result = run_deterministic_simulation(
        num_rooms=num_rooms,
        initial_grid=initial_grid,
        initial_agent_room=initial_agent_room,
    )
    deterministic_steps = det_result.steps_taken

    # 2. Execute Monte Carlo batch
    runs: List[SingleRunResult] = []
    steps_list: List[int] = []

    for r_idx in range(1, num_runs + 1):
        res = run_single_stochastic_simulation(
            num_rooms=num_rooms,
            initial_grid=initial_grid,
            initial_agent_room=initial_agent_room,
            move_success_prob=move_success_prob,
            slip_stay_prob=slip_stay_prob,
            slip_back_prob=slip_back_prob,
            max_steps=max_steps_per_run,
            run_id=r_idx,
            rng=rng,
        )
        runs.append(res)
        steps_list.append(res.steps_taken)

    # 3. Compute empirical statistics using Python standard `statistics` module
    mean_val = statistics.mean(steps_list)
    median_val = statistics.median(steps_list)
    stdev_val = statistics.stdev(steps_list) if len(steps_list) > 1 else 0.0
    min_val = min(steps_list)
    max_val = max(steps_list)

    # 4. Performance penalty metrics
    absolute_penalty = mean_val - deterministic_steps
    percentage_penalty = (
        (absolute_penalty / deterministic_steps) * 100.0 if deterministic_steps > 0 else 0.0
    )

    # 5. Theoretical expected steps
    theoretical_expected = calculate_theoretical_expected_steps(
        num_rooms=num_rooms,
        move_success_prob=move_success_prob,
        slip_back_prob=slip_back_prob,
    )

    return MonteCarloExperimentResult(
        num_runs=num_runs,
        grid_size=num_rooms,
        runs=runs,
        steps_per_run=steps_list,
        mean_steps=mean_val,
        median_steps=median_val,
        stdev_steps=stdev_val,
        min_steps=min_val,
        max_steps=max_val,
        deterministic_steps=deterministic_steps,
        absolute_penalty=absolute_penalty,
        percentage_penalty=percentage_penalty,
        theoretical_expected_steps=theoretical_expected,
    )
