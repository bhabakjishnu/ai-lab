def parse_grid_argument(grid_arg: str) -> List[List[str]]:
    """Parse grid string from CLI into a 2x2 list of statuses.

    Accepts formats:
      - "Dirty Clean, Dirty Dirty"
      - "D C, D D"
      - "Dirty,Clean;Dirty,Dirty"

    Args:
        grid_arg: Raw command-line string.

    Returns:
        2x2 nested list of normalized status strings.

    Raises:
        ValueError: If parsed dimensions are not 2x2 or statuses are invalid.
    """
    delimiters = [";", "\n", ", "]
    row_strings: List[str] = []

    if ";" in grid_arg:
        row_strings = [r.strip() for r in grid_arg.split(";") if r.strip()]
    elif "/" in grid_arg:
        row_strings = [r.strip() for r in grid_arg.split("/") if r.strip()]
    elif "," in grid_arg and " " not in grid_arg.replace(", ", ""):
        # e.g. "Dirty,Clean,Dirty,Dirty"
        tokens = [t.strip() for t in grid_arg.split(",") if t.strip()]
        if len(tokens) == 4:
            row_strings = [f"{tokens[0]} {tokens[1]}", f"{tokens[2]} {tokens[3]}"]
        else:
            row_strings = [grid_arg]
    else:
        # Split by comma or semicolon
        row_strings = [r.strip() for r in grid_arg.split(",") if r.strip()]

    parsed_grid: List[List[str]] = []
    for row_str in row_strings:
        raw_cells = [c.strip() for c in row_str.split() if c.strip()]
        # Expand shorthands 'D' -> 'Dirty', 'C' -> 'Clean'
        expanded_cells = []
        for cell in raw_cells:
            upper = cell.upper()
            if upper == "D":
                expanded_cells.append(STATUS_DIRTY)
            elif upper == "C":
                expanded_cells.append(STATUS_CLEAN)
            else:
                expanded_cells.append(normalize_status(cell))
        parsed_grid.append(expanded_cells)

    if len(parsed_grid) != 2 or any(len(row) != 2 for row in parsed_grid):
        raise ValueError(
            f"Expected a 2x2 grid configuration, but parsed {len(parsed_grid)}x"
            f"{[len(r) for r in parsed_grid]}. Example format: 'Dirty Clean, Dirty Dirty'"
        )

    return parsed_grid


def print_grid_visualization(grid: List[List[str]], agent_pos: Tuple[int, int]) -> None:
    """Print an ASCII graphical representation of the 2x2 grid with agent marker.

    Args:
        grid: 2D list of statuses.
        agent_pos: (row, col) position of the agent.
    """
    print("+---------------+---------------+")
    for r in range(2):
        lines_top = f"| ({r},0) {grid[r][0]:<5}    | ({r},1) {grid[r][1]:<5}    |"
        agent_0 = "[AGENT] " if (r, 0) == agent_pos else "        "
        agent_1 = "[AGENT] " if (r, 1) == agent_pos else "        "
        lines_bot = f"|    {agent_0}   |    {agent_1}   |"
        print(lines_top)
        print(lines_bot)
        print("+---------------+---------------+")


def run_interactive_simulation(
    grid: List[List[str]],
    start_pos: Tuple[int, int],
    sensor_failure_prob: float,
    seed: Optional[int],
) -> None:
    """Run interactive step-by-step simulation with live terminal prompts."""
    print("\n" + "=" * 70)
    print("      INTERACTIVE MODEL-BASED REFLEX AGENT SIMULATION")
    print("=" * 70)

    env = TwoByTwoGridEnvironment(
        initial_grid=grid,
        start_pos=start_pos,
        sensor_failure_prob=sensor_failure_prob,
        seed=seed,
    )
    agent = ModelBasedAgent(grid_dimensions=(2, 2), initial_pos=start_pos)

    step = 0
    while not agent.is_shutdown and step < 30:
        step += 1
        percept = env.get_percept()
        pos, status = percept
        sensor_failed = env.last_sensor_failed

        print(f"\n--- STEP {step} ---")
        print_grid_visualization(env.grid, env.agent_pos)

        failure_note = " [SENSOR FAILURE DETECTED!]" if sensor_failed else ""
        print(f"Agent Perception: Coordinate {pos} is {status}{failure_note}")

        action = agent.decide_action(percept)
        print(f"Internal Visited Set: {sorted(agent.visited)}")
        print(f"Internal World Model: {agent.model}")
        print(f"Action Chosen:        -> {action}")

        if action == ACTION_SHUTDOWN:
            print("\n" + "*" * 70)
            print(f"TERMINATION: {TERMINATION_MESSAGE}")
            print("*" * 70)
            break

        env.execute_action(action)
        input("Press [Enter] to advance to next step...")


def main() -> None:
    """Entry point for the Model-Based Reflex Agent runner."""
    parser = argparse.ArgumentParser(
        description="Run Model-Based Reflex Agent simulation on 2x2 grid environment.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Run standard sample scenario [[Dirty, Clean], [Dirty, Dirty]]:
  python run_model_based_agent.py

  # Custom grid:
  python run_model_based_agent.py --grid "Dirty Clean, Dirty Dirty"

  # Optional challenge: 20% sensor failure probability
  python run_model_based_agent.py --sensor-failure 0.2 --seed 42

  # Interactive walkthrough mode:
  python run_model_based_agent.py --interactive

  # Display Viva Voce study guide:
  python run_model_based_agent.py --viva
        """,
    )

    parser.add_argument(
        "--grid",
        type=str,
        default="Dirty Clean, Dirty Dirty",
        help="2x2 grid initial status (default: 'Dirty Clean, Dirty Dirty')",
    )
    parser.add_argument(
        "--start-row",
        type=int,
        default=0,
        choices=[0, 1],
        help="Agent starting row coordinate (0 or 1, default: 0)",
    )
    parser.add_argument(
        "--start-col",
        type=int,
        default=0,
        choices=[0, 1],
        help="Agent starting column coordinate (0 or 1, default: 0)",
    )
    parser.add_argument(
        "--sensor-failure",
        type=float,
        default=0.0,
        help="Probability [0.0 - 1.0] that Dirty is perceived as Clean (Optional Challenge)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for reproducible sensor noise",
    )
    parser.add_argument(
        "--interactive",
        action="store_true",
        help="Run simulation step-by-step with interactive prompts",
    )
    parser.add_argument(
        "--viva",
        action="store_true",
        help="Display curated Viva Voce theory notes and exit",
    )

    args = parser.parse_args()

    if args.viva:
        display_viva_notes()
        sys.exit(0)

    try:
        grid_data = parse_grid_argument(args.grid)
    except ValueError as e:
        print(f"Error parsing --grid argument: {e}", file=sys.stderr)
        sys.exit(1)

    start_pos = (args.start_row, args.start_col)

    if args.interactive:
        run_interactive_simulation(
            grid=grid_data,
            start_pos=start_pos,
            sensor_failure_prob=args.sensor_failure,
            seed=args.seed,
        )
        sys.exit(0)

    print("================================================================================")
    print("                    MODEL-BASED REFLEX AGENT SIMULATION")
    print("                    Practical Question No. 3 (2x2 Grid)")
    print("================================================================================")
    print(f"Initial 2x2 Grid State:    {grid_data}")
    print(f"Agent Starting Position:   {start_pos}")
    if args.sensor_failure > 0:
        print(f"Sensor Failure Rate:       {args.sensor_failure * 100:.1f}% (Seed: {args.seed})")
    print("--------------------------------------------------------------------------------")
    print("Initial Grid Visualization:")
    print_grid_visualization(grid_data, start_pos)
    print("\nExecuting Autonomous Model-Based Cleaning Routine...\n")

    env = TwoByTwoGridEnvironment(
        initial_grid=grid_data,
        start_pos=start_pos,
        sensor_failure_prob=args.sensor_failure,
        seed=args.seed,
    )
    agent = ModelBasedAgent(grid_dimensions=(2, 2), initial_pos=start_pos)

    result = run_model_based_simulation(env, agent)

    for record in result.history:
        print(record.format_trace())

    print("\n--------------------------------------------------------------------------------")
    print(f"Sample Output: {result.termination_message}")
    print("--------------------------------------------------------------------------------")
    print("Final Grid Visualization:")
    print_grid_visualization(result.final_grid, result.final_pos)
    print("\nFinal Performance Summary:")
    print(result.summary())
    print("================================================================================")


if __name__ == "__main__":
    main()
